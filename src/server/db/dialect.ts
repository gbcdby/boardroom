/**
 * SQL 方言抽象（F1 #46）。
 *
 * 收敛 SQLite 与 PostgreSQL 之间的 DDL/DML 差异面：
 * - 参数占位符（统一源码写 `?`，PG 渲染为 `$n`，引号内不替换）；
 * - 事务语句（SQLite 用 `BEGIN IMMEDIATE` 提前拿写锁，PG 用 `BEGIN`）；
 * - 类型与自增映射（text/integer/boolean/json/timestamp/自增主键）；
 * - 迁移版本表基线 DDL（迁移运行器共用）。
 *
 * 阶段 1 的业务表 DDL 仍走 SQLite（数据迁移属于 M1 #54）；
 * 本模块是 M1 按方言重写 DDL/DML 的落点。
 */
import type { DbDriverKind } from "../config.ts";
import { MIGRATION_TABLE } from "./migrate.ts";

/** 跨方言的列类型语义名。 */
export type ColumnType = "integer_pk" | "integer" | "text" | "boolean" | "json" | "timestamp";

export interface SqlDialect {
  /** 方言名，与驱动 kind 一致。 */
  readonly name: DbDriverKind;
  /**
   * 把统一 `?` 占位符渲染为本方言的参数标记。
   * SQLite 原样返回；PostgreSQL 依次替换为 `$1、$2…`（字符串字面量与
   * 双引号标识符内的 `?` 不替换）。
   */
  renderParameters(sql: string): string;
  /** 写事务开始语句。 */
  beginTransaction(): string;
  /** 事务提交语句。 */
  commit(): string;
  /** 事务回滚语句。 */
  rollback(): string;
  /** 语义列类型 → 本方言 DDL 片段。 */
  columnType(type: ColumnType): string;
  /** 迁移版本表基线 DDL（幂等，可安全重复执行）。 */
  migrationTableDdl(): string;
}

/**
 * 统一 SQL → 参数化方言 SQL：只替换引号之外的 `?`。
 *
 * 引号处理：`'…'` 字符串字面量（含 `''` 转义）、`"…"` 标识符；
 * 未闭合引号时原样报错，避免生成语义漂移的 SQL。
 */
export function renderPlaceholders(sql: string): string {
  let out = "";
  let index = 0;
  let quote: string | null = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote !== null) {
      out += ch;
      if (ch === quote) {
        // SQL 标准的双写转义：'' 或 "" 表示字面引号本身。
        if (sql[i + 1] === quote) {
          out += sql[++i];
        } else {
          quote = null;
        }
      }
      continue;
    }
    if (ch === "'" || ch === '"') {
      quote = ch;
      out += ch;
      continue;
    }
    if (ch === "?") {
      index += 1;
      out += `$${index}`;
      continue;
    }
    out += ch;
  }
  if (quote !== null) {
    throw new DialectError(`SQL 中存在未闭合的引号（${quote}），无法渲染参数占位符：${sql.slice(0, 80)}…`);
  }
  return out;
}

/** 方言层的定义错误（SQL 写法不支持等）。 */
export class DialectError extends Error {
  override readonly name = "DialectError";
}

const BEGIN_IMMEDIATE = "BEGIN IMMEDIATE";
const COMMON = {
  commit: (): string => "COMMIT",
  rollback: (): string => "ROLLBACK",
} as const;

/** SQLite 方言：阶段 1 既有行为基线。 */
export const sqliteDialect: SqlDialect = {
  name: "sqlite",
  renderParameters: (sql) => sql,
  beginTransaction: () => BEGIN_IMMEDIATE,
  ...COMMON,
  columnType: (type) => {
    switch (type) {
      case "integer_pk":
        return "INTEGER PRIMARY KEY";
      case "integer":
        return "INTEGER";
      case "text":
        return "TEXT";
      case "boolean":
        return "INTEGER";
      case "json":
        return "TEXT";
      case "timestamp":
        return "TEXT";
    }
  },
  migrationTableDdl: () =>
    `CREATE TABLE IF NOT EXISTS ${MIGRATION_TABLE} (
  version    ${sqliteDialect.columnType("integer_pk")},
  name       ${sqliteDialect.columnType("text")} NOT NULL,
  checksum   ${sqliteDialect.columnType("text")} NOT NULL,
  applied_at ${sqliteDialect.columnType("timestamp")} NOT NULL
);`,
};

/** PostgreSQL 方言：本票接入 connect/migrate/query 与基线迁移；业务表重写见 M1 #54。 */
export const postgresDialect: SqlDialect = {
  name: "postgres",
  renderParameters: (sql) => renderPlaceholders(sql),
  beginTransaction: () => "BEGIN",
  ...COMMON,
  columnType: (type) => {
    switch (type) {
      case "integer_pk":
        // GENERATED BY DEFAULT：保留运行器显式写入版本号的用法，同时是 PG 的自增惯用法。
        return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
      case "integer":
        return "INTEGER";
      case "text":
        return "TEXT";
      case "boolean":
        return "BOOLEAN";
      case "json":
        return "JSONB";
      case "timestamp":
        return "TIMESTAMPTZ";
    }
  },
  migrationTableDdl: () =>
    `CREATE TABLE IF NOT EXISTS ${MIGRATION_TABLE} (
  version    ${postgresDialect.columnType("integer_pk")},
  name       ${postgresDialect.columnType("text")} NOT NULL,
  checksum   ${postgresDialect.columnType("text")} NOT NULL,
  applied_at ${postgresDialect.columnType("timestamp")} NOT NULL
);`,
};

// 此函数只消费下列私有编译字面量；不导出，也不接受 caller 数据。
function freezeSource<T>(value: T): T {
  if (value !== null && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) freezeSource(child);
  }
  return value;
}


// Independent, hand-ordered canonical wire vector; this is not generated by the candidate encoder.
const enterBytes = Buffer.from('{"controlProof":null,"event":"enter","evidence":[],"fenceEpoch":2,"formatVersion":3,"frozen":null,"kind":"journal","migrationId":"a12","ownerGeneration":7,"phase":"planned","plan":{"bytes":"123","ref":"plans/' + "3".repeat(64) + '.json","sha256":"' + "3".repeat(64) + '"},"previous":null,"requestDigest":"' + "4".repeat(64) + '","requestId":"enter","sequence":1,"snapshot":null,"source":{"databaseInstanceId":"' + "1".repeat(32) + '","identityDigest":"' + "2".repeat(64) + '","kind":"sqlite"},"sourceClients":null}');
const enter = () => JSON.parse(enterBytes.toString()) as Record<string, unknown>;
const invalid = (error: unknown) => error instanceof MaintenanceFailure && error.code === "journal_invalid";

test("A12-R01: private v3 candidate has exact canonical bytes and an explicit untrusted data type", () => {
  const parsed = parseControlJournalCandidate(enter());
  assert.equal(parsed.formatVersion, 3);
  assert.equal(parsed.controlProof, null);
  assert.deepEqual(encodeControlJournalCandidate(parsed), enterBytes);
  assert.equal(sha256(enterBytes), "4d57a26f58a3460ab7b826ceaa06ba688eb6ea9d50e563a93d092437f468af73");
  const reference = { ref: `journals/a12/1-${sha256(enterBytes)}.json`, sha256: sha256(enterBytes), bytes: String(enterBytes.length) };
  assert.deepEqual(readControlJournalCandidate(reference, enterBytes), parsed);
  for (const bytes of [Buffer.concat([enterBytes, Buffer.from("\n")]), Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), enterBytes])]) {
    const digest = sha256(bytes);
    assert.throws(() => readControlJournalCandidate({ ref: `journals/a12/1-${digest}.json`, sha256: digest, bytes: String(bytes.length) }, bytes), invalid);
  }
  assert.throws(() => readControlJournalCandidate({ ...reference, bytes: "0" }, enterBytes), invalid);
  assert.throws(() => readControlJournalCandidate({ ...reference, ref: `journals/a12/2-${reference.sha256}.json` }, enterBytes), invalid);
});


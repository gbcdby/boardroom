function historicalCapture(encoding = "UTF-8") {
  const f = controlVector({ encoding }), client = historicalClient(f);
  const roster = { ...f.roster, rows: [client.row] };
  const captured = { ...f.captured, sourceClients: roster, frozen: { ...f.captured.frozen, sourceClientsDigest: sha256(canonicalJson(roster)) },
    controlProof: { ...f.captured.controlProof, facts: { ...f.facts, beforeCount: "1", beforeRowsDigest: f.rowsDigest([client.row]), clients: [client.fact] } } };
  f.captured.frozen.sourceClientsDigest = captured.frozen.sourceClientsDigest;
  const capture = f.pack("journal", captured);
  return { f, client, roster, captured, capture };
}


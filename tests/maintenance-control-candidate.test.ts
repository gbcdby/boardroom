  const vectors = [linux.captured, darwin.captured, pg.captured, activeCapture, observed, legacyVector().bridge];
  let checks = 0;
  for (const vector of vectors) {
    assert.doesNotThrow(() => parseControlJournalCandidate(vector));
    const paths: (string | number)[][] = [];
    const visit = (value: unknown, path: (string | number)[]) => {
      if (Array.isArray(value)) value.forEach((item, index) => visit(item, [...path, index]));
      else if (value !== null && typeof value === "object") { paths.push(path); for (const [key, item] of Object.entries(value)) visit(item, [...path, key]); }
    };
    visit(vector, []);
    for (const path of paths) {
      const original: any = path.reduce((value: any, key) => value[key], vector);
      for (const key of ["__unknown_candidate_field", ...Object.keys(original)]) {
        const changed: any = structuredClone(vector), target: any = path.reduce((value: any, key) => value[key], changed);
        if (key === "__unknown_candidate_field") target[key] = "must reject"; else delete target[key];
        assert.throws(() => parseControlJournalCandidate(changed), invalid, `${path.join(".")}/${key}`); checks++;
      }
    }
  }
  t.diagnostic(`${checks} fixed-vector required-field/unknown-field rejection controls`);

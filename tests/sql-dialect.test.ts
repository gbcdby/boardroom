/**
 * F1（#46）：SQL 方言抽象的 seam 测试。
 *
 * 方言是 DbDriver 的公共组成部分：占位符渲染、事务语句、类型/自增/JSON
 * 映射与迁移版本表基线 DDL。期望值来自票面约定的惯用法字面量。
 */
import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { postgresDialect, renderPlaceholders, sqliteDialect } from "../src/server/db/dialect.ts";
import { createDbDriver } from "../src/server/db/driver.ts";
import { MIGRATION_TABLE } from "../src/server/db/migrate.ts";

test("sqlite 方言保持统一 SQL 原样（阶段 1 行为不变）", () => {
  assert.equal(sqliteDialect.renderParameters("SELECT * FROM t WHERE a = ? AND b = ?"), "SELECT * FROM t WHERE a = ? AND b = ?");
  assert.equal(sqliteDialect.beginTransaction(), "BEGIN IMMEDIATE");
});

test("postgres 方言把 ? 按出现顺序渲染为 $n", () => {
  assert.equal(
    postgresDialect.renderParameters("INSERT INTO t (a, b) VALUES (?, ?)"),
    "INSERT INTO t (a, b) VALUES ($1, $2)",
  );
  assert.equal(postgresDialect.beginTransaction(), "BEGIN");
});

test("引号字面量与标识符内的 ? 不参与占位符替换", () => {
  assert.equal(
    renderPlaceholders("SELECT ? , 'a ? b', \"col?x\" , '?' , \"?\""),
    "SELECT $1 , 'a ? b', \"col?x\" , '?' , \"?\"",
  );
});

test("未闭合引号的 SQL 报错而不是产出漂移 SQL", () => {
  assert.throws(() => renderPlaceholders("SELECT ? FROM 'unclosed"), {
    name: "DialectError",
  });
});

test("类型映射：自增主键/JSON/布尔/时间戳按方言收敛", () => {
  assert.equal(sqliteDialect.columnType("integer_pk"), "INTEGER PRIMARY KEY");
  assert.equal(sqliteDialect.columnType("json"), "TEXT");
  assert.equal(sqliteDialect.columnType("boolean"), "INTEGER");
  assert.equal(sqliteDialect.columnType("timestamp"), "TEXT");

  assert.equal(postgresDialect.columnType("integer_pk"), "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  assert.equal(postgresDialect.columnType("json"), "JSONB");
  assert.equal(postgresDialect.columnType("boolean"), "BOOLEAN");
  assert.equal(postgresDialect.columnType("timestamp"), "TIMESTAMPTZ");
});

test("迁移版本表基线 DDL 两方言一致命名，SQLite 侧可直接执行且幂等", async () => {
  const dir = await mkdtemp(path.join(tmpdir(), "agent-studio-dialect-"));
  try {
    const driver = createDbDriver({ dbDriver: "sqlite", dataDir: dir });
    await driver.connect();
    try {
      await driver.exec(sqliteDialect.migrationTableDdl());
      await driver.exec(sqliteDialect.migrationTableDdl()); // 重复执行不报错
      const rows = await driver.query<{ name: string }>(
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?",
        [MIGRATION_TABLE],
      );
      assert.equal(rows.length, 1);
      assert.match(sqliteDialect.migrationTableDdl(), /CREATE TABLE IF NOT EXISTS schema_migrations/);
      assert.match(postgresDialect.migrationTableDdl(), /CREATE TABLE IF NOT EXISTS schema_migrations/);
    } finally {
      await driver.close();
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
